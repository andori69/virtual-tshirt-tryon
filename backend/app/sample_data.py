"""Clearly-labelled SAMPLE data: a drawn T-shirt photo stand-in that still goes through the real pipeline."""
import io

import numpy as np
from PIL import Image, ImageDraw, ImageFilter

# Outline of a front-view T-shirt on a 1000x1000 grid (clockwise from left neckline).
TEE_OUTLINE = [
    (400, 120), (300, 150), (130, 260), (200, 420), (270, 380), (270, 900),
    (730, 900), (730, 380), (800, 420), (870, 260), (700, 150), (600, 120),
    (575, 165), (500, 185), (425, 165),
]


def sample_tee_photo(color: tuple[int, int, int], size: int = 1000, background=(232, 230, 226), seed: int = 0) -> bytes:
    rng = np.random.default_rng(seed)
    bg = np.full((size, size, 3), background, np.uint8)
    bg = np.clip(bg.astype(int) + rng.normal(0, 3, bg.shape), 0, 255).astype(np.uint8)  # mild sensor noise
    img = Image.fromarray(bg)
    s = size / 1000
    pts = [(x * s, y * s) for x, y in TEE_OUTLINE]
    shadow = Image.new("L", img.size, 0)
    ImageDraw.Draw(shadow).polygon([(x + 8 * s, y + 10 * s) for x, y in pts], fill=90)
    img.paste((120, 118, 115), mask=shadow.filter(ImageFilter.GaussianBlur(12 * s)))
    draw = ImageDraw.Draw(img)
    draw.polygon(pts, fill=color)
    shade = tuple(max(0, c - 35) for c in color)
    draw.line([(425 * s, 165 * s), (500 * s, 185 * s), (575 * s, 165 * s)], fill=shade, width=int(10 * s))  # collar
    draw.line([(270 * s, 380 * s), (300 * s, 150 * s)], fill=shade, width=int(3 * s))  # sleeve seams
    draw.line([(730 * s, 380 * s), (700 * s, 150 * s)], fill=shade, width=int(3 * s))
    buf = io.BytesIO()
    img.save(buf, format="JPEG", quality=92)
    return buf.getvalue()


